<?php

/**
 * Regenerates administrator/components/com_appointments/lib/ from the pinned
 * sabre/dav release: installs composer.lock, prefixes every symbol with
 * php-scoper (scoper.inc.php) and writes the files, the licences and the
 * autoload map. The CI job runs it and fails on any difference to the
 * committed lib/, so lib/ is always exactly what this script produces.
 *
 * Usage (from anywhere):
 *   php com_appointments/tests/tools/sabre/generate.php
 *
 * Environment:
 *   COMPOSER_BIN  Command that runs Composer (default: composer).
 *   PHP_BIN       PHP binary for php-scoper (default: the running PHP).
 *
 * Needs PHP 8.2 or newer for php-scoper; the generated code itself runs on
 * PHP 8.1, which composer.json pins as the platform.
 */

declare(strict_types=1);

const PREFIX = 'Advans\\Component\\Appointments\\Vendor\\';

$tool = __DIR__;
$lib = dirname($tool, 3) . '/administrator/components/com_appointments/lib';
$build = $tool . '/.build';

if (!is_dir($lib)) {
    fail("Target folder not found: {$lib}");
}

$composer = getenv('COMPOSER_BIN') ?: 'composer';
$php = getenv('PHP_BIN') ?: PHP_BINARY;
$composerFlags = '--no-interaction --no-progress --prefer-dist --no-plugins --no-scripts';

run($composer . ' install --no-dev ' . $composerFlags, $tool);
run($composer . ' install --no-dev ' . $composerFlags, $tool . '/scoper');

removeTree($build);
run(
    escapeshellarg($php) . ' ' . escapeshellarg($tool . '/scoper/vendor/humbug/php-scoper/bin/php-scoper')
    . ' add-prefix --config=' . escapeshellarg($tool . '/scoper.inc.php') . ' --force --no-interaction --no-ansi --quiet',
    $tool
);

$scoped = $build . '/scoped';

if (!is_dir($scoped . '/sabre/dav')) {
    fail('php-scoper did not write the expected output below ' . $scoped);
}

$installed = json_decode((string) file_get_contents($tool . '/vendor/composer/installed.json'), true, 512, JSON_THROW_ON_ERROR);
$packages = $installed['packages'] ?? $installed;
usort($packages, static fn (array $a, array $b): int => strcmp($a['name'], $b['name']));

// Start from an empty lib/, so a file removed upstream disappears here too.
removeTree($lib);
mkdir($lib, 0755, true);

$psr4 = [];
$files = [];
$versions = [];

foreach ($packages as $package) {
    $name = $package['name'];

    if (!preg_match('#^(sabre/[a-z]+|psr/log)$#', $name)) {
        fail("Unexpected package in the lock file: {$name}");
    }

    $versions[$name] = [
        'version' => ltrim((string) $package['version'], 'v'),
        'license' => implode(' OR ', (array) ($package['license'] ?? [])),
    ];

    copyTree($scoped . '/' . $name, $lib . '/' . $name);

    foreach (['LICENSE', 'LICENSE.md', 'LICENSE.txt'] as $licence) {
        if (is_file($tool . '/vendor/' . $name . '/' . $licence)) {
            writeFile($lib . '/' . $name . '/LICENSE', normalise((string) file_get_contents($tool . '/vendor/' . $name . '/' . $licence)));
            break;
        }
    }

    if (!is_file($lib . '/' . $name . '/LICENSE')) {
        fail("No licence file in {$name}");
    }

    foreach ($package['autoload']['psr-4'] ?? [] as $namespace => $path) {
        $psr4[PREFIX . $namespace] = $name . '/' . trim((string) $path, '/');
    }

    foreach ($package['autoload']['files'] ?? [] as $path) {
        if (!is_file($lib . '/' . $name . '/' . $path)) {
            fail("Autoloaded file missing after scoping: {$name}/{$path}");
        }

        $files[] = $name . '/' . $path;
    }
}

// Longest namespace first, so Sabre\Event\ wins over Sabre\.
uksort($psr4, static fn (string $a, string $b): int => [\strlen($b), $a] <=> [\strlen($a), $b]);

$map = "<?php\n\n"
    . "/**\n"
    . " * @package     Appointments Component\n"
    . " * @subpackage  Administrator\n"
    . " * @copyright   (C) 2026 Advans IT Solutions GmbH <https://advans.ch>\n"
    . " * @license     GNU General Public License version 3 or later; see LICENSE.txt\n"
    . " * SPDX-License-Identifier: GPL-3.0-or-later\n"
    . " *\n"
    . " * Generated by tests/tools/sabre/generate.php. Do not edit.\n"
    . " *\n"
    . " * Autoload map of the bundled, namespace-prefixed libraries, read by\n"
    . " * Advans\\Component\\Appointments\\Administrator\\Helper\\Team\\VendorAutoloader.\n"
    . " * Paths are relative to this folder.\n"
    . " */\n\n"
    . "defined('_JEXEC') or die;\n\n"
    . 'return ' . export(['packages' => $versions, 'psr4' => $psr4, 'files' => $files]) . ";\n";

writeFile($lib . '/autoload.php', $map);
writeFile($lib . '/index.html', "<html><body bgcolor=\"#FFFFFF\"></body></html>\n");


removeTree($build);

echo 'lib/ regenerated: ' . implode(', ', array_map(static fn (string $n, array $v): string => $n . ' ' . $v['version'], array_keys($versions), $versions)) . "\n";

/**
 * Runs a shell command in a folder and stops on failure.
 */
function run(string $command, string $cwd): void
{
    $process = proc_open($command, [1 => STDOUT, 2 => STDERR], $pipes, $cwd);

    if (!\is_resource($process) || proc_close($process) !== 0) {
        fail("Command failed: {$command}");
    }
}

function copyTree(string $from, string $to): void
{
    if (!is_dir($from)) {
        fail("Scoped package missing: {$from}");
    }

    $entries = iterator_to_array(new RecursiveIteratorIterator(new RecursiveDirectoryIterator($from, FilesystemIterator::SKIP_DOTS)));
    ksort($entries);

    foreach ($entries as $path => $entry) {
        if ($entry->isFile()) {
            writeFile($to . substr(str_replace('\\', '/', $path), \strlen(str_replace('\\', '/', $from))), normalise((string) file_get_contents($path)));
        }
    }
}

function writeFile(string $path, string $contents): void
{
    if (!is_dir(\dirname($path))) {
        mkdir(\dirname($path), 0755, true);
    }

    file_put_contents($path, $contents);
}

/**
 * LF line endings and exactly one final newline, whatever the platform wrote.
 */
function normalise(string $contents): string
{
    return rtrim(str_replace(["\r\n", "\r"], "\n", $contents), "\n") . "\n";
}

function removeTree(string $path): void
{
    if (!file_exists($path)) {
        return;
    }

    foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST) as $entry) {
        $entry->isDir() ? rmdir($entry->getPathname()) : unlink($entry->getPathname());
    }

    rmdir($path);
}

/**
 * var_export() with short arrays and four-space indentation.
 */
function export(mixed $value, int $depth = 0): string
{
    if (!\is_array($value)) {
        return var_export($value, true);
    }

    $pad = str_repeat('    ', $depth + 1);
    $list = array_is_list($value);
    $lines = [];

    foreach ($value as $key => $item) {
        $lines[] = $pad . ($list ? '' : var_export($key, true) . ' => ') . export($item, $depth + 1) . ',';
    }

    return $lines === [] ? '[]' : "[\n" . implode("\n", $lines) . "\n" . str_repeat('    ', $depth) . ']';
}

function fail(string $message): never
{
    fwrite(STDERR, $message . "\n");
    exit(1);
}
